#!/usr/bin/env node
// Generates the gitignored `src/environments/environment.ts` from `.env`, before every `ng serve` /
// `ng build` (wired as a prefix step in package.json). Angular has no built-in `.env` support (unlike
// Vite's `import.meta.env`), so this reproduces the same "token never committed, read at build time"
// contract other samples get from their bundler's `define` — via Angular's own environment-file
// convention instead.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const envPath = `${root}/.env`;
const outPath = `${root}/src/environments/environment.ts`;

function parseEnvFile(path) {
  const out = {};
  if (!existsSync(path)) return out;
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    const trimmed = line.trim();
    if (trimmed === '' || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    out[trimmed.slice(0, eq).trim()] = trimmed.slice(eq + 1).trim();
  }
  return out;
}

const fromFile = parseEnvFile(envPath);
const appToken = process.env.BUGSEE_APP_TOKEN ?? fromFile.BUGSEE_APP_TOKEN ?? '';
const endpoint = process.env.BUGSEE_ENDPOINT ?? fromFile.BUGSEE_ENDPOINT ?? 'https://apidev.bugsee.com';

if (appToken === '') {
  // eslint-disable-next-line no-console
  console.warn('[generate-environment] BUGSEE_APP_TOKEN is empty — copy .env.example to .env and set it.');
}

let buildCounter = process.env.APP_BUILD ?? 'dev';
const counterFile = `${root}/.build-counter`;
if (process.env.APP_BUILD === undefined && existsSync(counterFile)) {
  buildCounter = readFileSync(counterFile, 'utf8').trim() || 'dev';
}

const content = `// GENERATED by scripts/generate-environment.mjs from .env — do not edit, do not commit (gitignored).
export const environment = {
  bugseeAppToken: ${JSON.stringify(appToken)},
  bugseeEndpoint: ${JSON.stringify(endpoint)},
  appBuild: ${JSON.stringify(buildCounter)},
};
`;

writeFileSync(outPath, content);
// eslint-disable-next-line no-console
console.log(`[generate-environment] wrote ${outPath} (endpoint=${endpoint}, appBuild=${buildCounter})`);
